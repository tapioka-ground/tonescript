//! 曲の読み込み。
//!
//! 曲ファイルは Rhai で書く。Python 版が `.py` だったのと同じ役割で、
//! 「式が書ける」ことを残したまま、再コンパイル無しで差し替えられる。
//!
//! なぜデータ形式（TOML など）にしなかったか
//! ------------------------------------------
//! 元の曲ファイルには、こういう書き方が普通に出てくる。
//!
//! ```text
//! 'octa': [(i, 2, o) for i in range(0, 16, 2) for o in (0, 12)]
//! ```
//!
//! 「2つおきに、根音とその1オクターブ上を置く」という意図がそのまま
//! 1行になっている。これをデータで書くと 16 行の数字の羅列になり、
//! 何をしたかったのかが読めなくなる。曲は設定ではなく、書きものに近い。
//!
//! 安全のために、曲ファイルからはファイルもネットワークも触れないように
//! してある（Rhai の既定でそもそも触れないが、実行の上限も入れてある）。

